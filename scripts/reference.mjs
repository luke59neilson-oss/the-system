// MU.6 (D272): embeds docs/reference/primal-hunter/*.csv into the server as
// apps/server/src/reference/lists.generated.ts, so the server, the desktop
// bundle and the tests all read the same lists with no files to ship.
// Run `npm run reference` after editing a list; a unit test fails until then.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
export const LISTS = {
  skills: 'skills.csv',
  items: 'items.csv',
  creatures: 'creatures.csv',
  classes: 'professions-classes.csv',
};
export const OUT = path.join(root, 'apps/server/src/reference/lists.generated.ts');

export function render() {
  const dir = path.join(root, 'docs/reference/primal-hunter');
  const body = Object.entries(LISTS)
    .map(
      ([key, file]) => `  ${key}: ${JSON.stringify(readFileSync(path.join(dir, file), 'utf8'))},`,
    )
    .join('\n');
  return [
    '// Generated by `npm run reference` from docs/reference/primal-hunter/*.csv. Do not edit.',
    '// prettier-ignore',
    'export const REFERENCE_CSV = {',
    body,
    '} as const;',
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  writeFileSync(OUT, render());
  console.log(`wrote ${path.relative(root, OUT)}`);
}
